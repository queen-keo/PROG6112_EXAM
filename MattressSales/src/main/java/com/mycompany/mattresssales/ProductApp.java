    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        
        try {

        // Get customer name
        String customerName =
                txtName.getText();

        // Get selected product
        String productName = jComboBoxProduct.getSelectedItem().toString();

        // Get product price
        double price =
                Double.parseDouble(txtPrice.getText());

        // Validate information
        if (customerName.trim().isEmpty() || price <= 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter valid customer details and price."
            );

            return;
        }

        // Create ProductCalculations object
        ProductCalculations calculations =
                new ProductCalculations(price);

        // Get calculations
        double vat = calculations.GetVat();

        double commission =
                calculations.GetCommission();

        double total = calculations.GetTotal();

        // Prepare report
        String message =
                "Customer Name: " + customerName
                + "\nProduct: " + productName
                + "\nVAT: R " + String.format("%.1f", vat)
                + "\nCOMMISSION: R "
                + String.format("%.1f", commission)
                + "\nTOTAL: R "
                + String.format("%.1f", total);

        // Display message
        javax.swing.JOptionPane.showMessageDialog(
                this,
                message,
                "Product Sales",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        // Save information to data.txt
        try (java.io.PrintWriter writer =
                new java.io.PrintWriter(
                new java.io.FileWriter("data.txt", true))) {

            writer.println("DATA LOG");
            writer.println("****************************************");
            writer.println("Customer Name: " + customerName);
            writer.println("Product: " + productName);
            writer.println("VAT: R " + String.format("%.1f", vat));
            writer.println("COMMISSION: R "
                    + String.format("%.1f", commission));
            writer.println("TOTAL: R "
                    + String.format("%.1f", total));
            writer.println("****************************************");
            writer.println();

        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter a valid numerical product price."
        );

    } catch (java.io.IOException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error saving information to data.txt: "
                + e.getMessage()
        );
    }

    }//GEN-LAST:event_btnProcessActionPerformed

